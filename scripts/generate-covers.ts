import {
  existsSync,
  mkdirSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { processPortrait } from "../src/artwork/portrait";
import { renderArt } from "../src/artwork/render";
import {
  artistArt,
  genreArt,
  releaseArt,
  songArt,
  type CoverArt,
} from "../src/content/artwork";
import { portfolio } from "../src/content/portfolio";

// Writes every generated cover into public/covers and, when a portrait of
// Darshil exists at public/photos/darshil-jain.{jpg,jpeg,png,webp}, its
// responsive AVIF/WebP/JPEG variants plus src/content/portrait.generated.ts.
const root = fileURLToPath(new URL("..", import.meta.url));
const publicDir = join(root, "public");

const covers: CoverArt[] = [
  artistArt,
  ...portfolio.collections.map(releaseArt),
  ...portfolio.caseStudies.map(songArt),
  ...portfolio.genres.map(genreArt),
];

rmSync(join(publicDir, "covers"), { recursive: true, force: true });
for (const art of covers) {
  const file = join(publicDir, art.src);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, renderArt(art));
}
console.log(`Wrote ${covers.length} covers`);

const photosDir = join(publicDir, "photos");
const source = existsSync(photosDir)
  ? readdirSync(photosDir).find((file) =>
      /^darshil-jain\.(jpe?g|png|webp)$/i.test(file),
    )
  : undefined;

const portraitModule = join(root, "src/content/portrait.generated.ts");
const header =
  "// Generated by scripts/generate-covers.ts. Do not edit by hand.\n";
const portrait = source
  ? await processPortrait(
      join(photosDir, source),
      join(photosDir, "generated"),
      "/photos/generated",
    )
  : null;

writeFileSync(
  portraitModule,
  `${header}import type { Portrait } from "./types";\n\nexport const portrait: Portrait | null = ${JSON.stringify(portrait, null, 2)};\n`,
);
console.log(
  portrait
    ? `Processed portrait ${source} into ${portrait.variants.length} sizes`
    : "No portrait found; the artist keeps generated artwork.",
);
